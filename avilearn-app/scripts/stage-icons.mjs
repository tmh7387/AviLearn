// Curated set for training slides. Add a name here, then run: node scripts/stage-icons.mjs
import { writeFileSync } from 'node:fs';
const NAMES = [
  'clipboard-check','clipboard-list','search','scan-search','file-search','file-text','book-open','graduation-cap',
  'link','network','workflow','git-branch','route','layers','list-checks','list-ordered','target','crosshair',
  'gauge','chart-line','chart-column','trending-up','scale','triangle-alert','shield-check','shield','lock',
  'plane','plane-takeoff','plane-landing','users','user','user-check','messages-square','message-circle','handshake',
  'lightbulb','wrench','settings','cog','refresh-cw','repeat','calendar','clock','flag','map','compass','eye',
  'circle-check','circle-question-mark','badge-check','award','building','hospital','hotel','heart-pulse','stethoscope','bell-ring',
];
const out = {};
for (const n of NAMES) {
  const m = await import(`lucide-react/dist/esm/icons/${n}.mjs`);
  out[n] = m.__iconNode.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}
const body = `/* Generated by scripts/stage-icons.mjs from lucide-react ${(await import('lucide-react/package.json', { with: { type: 'json' } })).default.version} (ISC licence, https://lucide.dev). Do not edit. */
export const ICON_NODES = ${JSON.stringify(out)} as const;
`;
writeFileSync(new URL('../src/lib/stage/icons.data.ts', import.meta.url), body);
console.log(Object.keys(out).length, 'icons');
